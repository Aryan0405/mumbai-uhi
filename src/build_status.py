def read_log(name):
    path = os.path.join(LOGS, name)
    with open(path, "rb") as f:
        head = f.read(2)
    if head == b"\xff\xfe":
        enc = "utf-16"
    elif head == b"\xfe\xff":
        enc = "utf-16"
    else:
        enc = "utf-8-sig"
    with open(path, "r", encoding=enc) as f:
        return f.read()


